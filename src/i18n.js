export function t(key, vars) {
  const dict = I18N[langState.lang] || I18N.th;
  let v = dict[key];
  if (v === undefined) v = I18N.th[key];
  if (typeof v === 'function') return v(vars || {});
  let s = v === undefined ? key : v;
  if (vars) {
    Object.keys(vars).forEach((k) => { s = s.split('{' + k + '}').join(vars[k]); });
  }
  return s;
}

export function setLang(l) {
  langState.lang = l === 'lo' ? 'lo' : 'th';
  try { localStorage.setItem(LANG_KEY, langState.lang); } catch (e) { /* ignore */ }
  document.documentElement.lang = langState.lang;
  document.title = t('title');
}
